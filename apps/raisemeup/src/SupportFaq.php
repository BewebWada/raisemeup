    // FAQPage構造化データ(検索結果でのリッチリザルト表示用)。回答文はHTMLリンクを含むことがあるため、
    // schema.org側にはstrip_tagsしたプレーンテキストを渡す
    public static function buildJsonLd(array $categories): array
    {
        $jsonLd = ['@context' => 'https://schema.org', '@type' => 'FAQPage', 'mainEntity' => []];
        foreach ($categories as $category) {
            foreach ($category['items'] as $item) {
                $jsonLd['mainEntity'][] = [
                    '@type' => 'Question',
                    'name' => $item['q'],
                    'acceptedAnswer' => ['@type' => 'Answer', 'text' => strip_tags($item['a'])],
                ];
            }
        }
        return $jsonLd;
    }

    // サポートbot(ClaudeClient::generateSupportReply)のシステムプロンプトに埋め込む知識ベース。
    // リンクを含む回答文をそのまま渡し、AIが案内時に同じURLを再利用できるようにする
    public static function buildKnowledgeBaseText(array $categories): string
    {
        $lines = [];
        foreach ($categories as $category) {
            $lines[] = '■ ' . $category['title'];
            foreach ($category['items'] as $item) {
                $lines[] = 'Q. ' . $item['q'];
                $lines[] = 'A. ' . $item['a'];
            }
            $lines[] = '';
        }
        return trim(implode("\n", $lines));
    }
